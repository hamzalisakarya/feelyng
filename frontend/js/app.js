const storageKey = "feelyng-language";

// TODO: WhatsApp Business Nummer eintragen und WhatsApp CTA wieder aktivieren.

const electricityEstimatorConfig = {
    apartmentBase: { 1: 1200, 2: 1900, 3: 2400, 4: 2600, 5: 3100, 6: 3500 },
    houseBase: { 1: 1800, 2: 2700, 3: 3500, 4: 3800, 5: 4500, 6: 5000 },
    // Bathroom hot water is used frequently and therefore has a stronger per-person effect.
    bathroomHotWaterPerPerson: 200,
    kitchenHotWaterPerPerson: 50,
    electricCookingAdjustment: 200,
    tumbleDryerAdjustment: 250,
    rangePercent: 8,
    roundingStep: 50
};

let currentLanguage = "de";
