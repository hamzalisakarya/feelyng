const storageKey = "feelyng-language";

// TODO: WhatsApp Business Nummer eintragen und WhatsApp CTA wieder aktivieren.

let currentLanguage = "de";
const menuToggle = document.querySelector(".menu-toggle");
const headerPanel = document.querySelector(".header-panel");

function updateMenuLabel(isOpen) {
    const label = menuToggle?.querySelector("[data-i18n='menuLabel']");
    if (label) {
        label.textContent = isOpen
            ? (currentLanguage === "de" ? "Menü schließen" : "Menüyü kapat")
            : translations[currentLanguage].menuLabel;
    }
}

function closeMenu() {
    menuToggle?.setAttribute("aria-expanded", "false");
    headerPanel?.classList.remove("is-open");
    document.body.classList.remove("menu-open");
    updateMenuLabel(false);
}

function setLanguage(language) {
    currentLanguage = translations[language] ? language : "de";
    document.documentElement.lang = currentLanguage;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const value = translations[currentLanguage][element.dataset.i18n];
        if (value) element.textContent = value;
    });

    document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
        const value = translations[currentLanguage][element.dataset.i18nAriaLabel];
        if (value) element.setAttribute("aria-label", value);
    });

    document.querySelectorAll("[data-language]").forEach((button) => {
        button.setAttribute("aria-pressed", String(button.dataset.language === currentLanguage));
    });

    try {
        localStorage.setItem(storageKey, currentLanguage);
    } catch {
        // German remains available if browser storage is disabled.
    }

    updateMenuLabel(menuToggle?.getAttribute("aria-expanded") === "true");
}

menuToggle?.addEventListener("click", () => {
    const isOpen = menuToggle.getAttribute("aria-expanded") !== "true";
    menuToggle.setAttribute("aria-expanded", String(isOpen));
    headerPanel?.classList.toggle("is-open", isOpen);
    document.body.classList.toggle("menu-open", isOpen);
    updateMenuLabel(isOpen);
});

document.querySelectorAll(".header-panel a").forEach((link) => {
    link.addEventListener("click", closeMenu);
});

document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeMenu();
});

document.querySelectorAll("[data-language]").forEach((button) => {
    button.addEventListener("click", () => setLanguage(button.dataset.language));
});

document.querySelectorAll("[data-current-year]").forEach((element) => {
    element.textContent = new Date().getFullYear();
});

let savedLanguage = "de";
try {
    savedLanguage = localStorage.getItem(storageKey) || "de";
} catch {
    // German is the default when browser storage is unavailable.
}

setLanguage(savedLanguage);
